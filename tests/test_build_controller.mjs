// Serial execution, coalesced replay, error cleanup and disposal through the public controller.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const window={};
vm.runInNewContext(readFileSync(new URL('../static/editors/source/build-controller.js',import.meta.url),'utf8'),{window});
const {SourceBuildController}=window;
const completed=[];
let started=0,release;
const controller=new SourceBuildController({onStarted:()=>started++,onFinished:state=>completed.push(state)});
const target={file:'original.tex'};
const task=controller.run(target,()=>new Promise(resolve=>{release=resolve;}));
assert.equal(started,1,'busy presentation is synchronous');
target.file='changed.tex';
assert.equal(controller.target.file,'original.tex');
assert.throws(()=>{controller.target.file='mutated.tex';},/read only|Cannot assign/);
await Promise.resolve();
let competing=0;
assert.equal(controller.run({file:'other.tex'},()=>competing++),task);
controller.queue();controller.queue();
release('done');
assert.equal(await task,'done');
assert.equal(competing,0);
assert.equal(completed.length,1);
assert.equal(completed[0].target.file,'original.tex');
assert.equal(completed[0].again,true,'repeated edits coalesce to one replay');
assert.equal(controller.pending,null);assert.equal(controller.target,null);
await assert.rejects(controller.run({file:null},async()=>{throw Error('build failed');}),/build failed/);
assert.equal(controller.pending,null);
assert.equal(completed.at(-1).again,false);
const next=controller.run({file:'next.tex'},()=>new Promise(resolve=>{release=resolve;}));
await Promise.resolve();controller.queue();controller.dispose();release();await next;
assert.equal(completed.length,2,'disposed host receives no completion/replay hooks');
await assert.rejects(controller.run({},()=>{}),/closed/);
const notStarted=new SourceBuildController();
const cancelled=notStarted.run({},()=>competing++);notStarted.dispose();await cancelled;
assert.equal(competing,0,'disposal before task start prevents IO');
const hookFailure=new SourceBuildController({onStarted:()=>{throw Error('render failed');}});
await assert.rejects(hookFailure.run({},()=>competing++),/render failed/);
assert.equal(hookFailure.pending,null);assert.equal(competing,0);
console.log('PASS: serial builds, immutable targets, coalesced replay, cleanup, synchronous busy state and disposal');
