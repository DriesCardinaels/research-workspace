import {Element,createDocument} from './support/pane-dom.mjs';
import {withPaneRuntime as withToolRuntime} from './support/tool-runtime.mjs';
// Test actual dialog actions with unsaved bibliography text and a deterministic HTTP boundary.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const document=createDocument(),body=document.body,calls=[],window={},modes={};
let checkError=false;
const localText='@article{key, title={Unsaved title}}';
const api=async(path,options={})=>{
  const data=options.body?JSON.parse(options.body):undefined;calls.push({path,data});
  if(path==='/api/bibliography/entries')return {entries:[{key:'key',title:'Unsaved title'}]};
  if(path==='/api/openalex/check'&&checkError)throw Error('Provider unavailable');
  if(path==='/api/openalex/check')return {works:[{title:'Candidate',authors:['Jane Doe'],year:'2026',venue:'Journal',url:'https://openalex.org/W1',comparison:[{field:'year',local:'2025',openalex:'2026',status:'review'}]}],lookup:'search'};
  if(path==='/api/openalex/search')return {works:[],lookup:'search'};
  if(path==='/api/settings/openalex')return {configured:options.method!=='PUT'||!!data.api_key};
  throw Error('Unexpected route '+path);
};
window.DraftMatch={};
const context=vm.createContext({window,api,document,CodeMirror:{defineMode:(n,m)=>modes[n]=m}});
vm.runInContext(withToolRuntime(readFileSync(new URL('../static/workspace.js',import.meta.url),'utf8')),context);
vm.runInContext(withToolRuntime(readFileSync(new URL('../static/bibliography.js',import.meta.url),'utf8')),context);
const all=n=>[n,...n.children.flatMap(all)];
const find=(d,text)=>all(d).find(n=>n.textContent===text);
const workspace=Object.create(window.Workspace.prototype);
workspace.file='references.bib';workspace.cites={bib_files:['references.bib']};workspace.o={api};
workspace.ensureFile=async f=>{assert.equal(f,'references.bib');return {doc:{getValue:()=>localText}};};
await window.openBibliography(workspace);
const dialog=body.children.at(-1),query=all(dialog).find(n=>n.getAttribute('aria-label')==='Search linked references');
query.value='key';query.oninput();
const matches=all(dialog).find(n=>n.className==='bibliography-suggestions');
assert.equal(matches.children.length,1,'bibkey autocomplete finds local entries');
query.value='Unsaved';query.oninput();assert.equal(matches.children.length,1,'title search uses unsaved bibliography');
query.value='Unrelated external title';query.oninput();
assert.equal(matches.children.length,0);assert.equal(find(dialog,'Check reference').disabled,true);
assert.ok(!calls.some(c=>c.path.startsWith('/api/openalex/')),'typing never contacts OpenAlex');
query.value='key';query.oninput();
await find(dialog,'Check reference').onclick();
assert.deepEqual(calls.find(c=>c.path==='/api/openalex/check').data,{text:localText,key:'key'});
assert.ok(find(dialog,'review'),'actual provider comparison is rendered');
assert.ok(!calls.some(c=>/draft\/file/.test(c.path)),'checking never saves source');
assert.ok(modes.bibtex,'BibTeX mode is registered');
checkError=true;
await find(dialog,'Check reference').onclick();
assert.ok(find(dialog,'Provider unavailable'),'provider errors remain in the checker');
assert.equal(find(dialog,'Check reference').disabled,false,'failed checks can be retried');
assert.equal(query.disabled,false,'local search recovers after provider failure');
checkError=false;
workspace.cites={bib_files:[]};
await window.openBibliography(workspace);
const emptyDialog=body.children.at(-1);
assert.ok(find(emptyDialog,'No bibliography file is linked to this paper.'));
assert.equal(find(emptyDialog,'Check reference').disabled,true);
assert.ok(!find(emptyDialog,'Search OpenAlex'),'unlinked projects cannot search the external catalog');
workspace.cites={bib_files:['references.bib']};
workspace.ensureFile=async()=>{throw Error('Read failed');};
await window.openBibliography(workspace);
assert.ok(find(body.children.at(-1),'Read failed'),'file failures are reported at the dialog boundary');
await window.openIntegrationSettings();
const settings=body.children.at(-1),input=all(settings).find(n=>n.tag==='input');input.value='test-key';
find(settings,'Save key').onclick();await new Promise(resolve=>setImmediate(resolve));
assert.equal(input.value,'','saved secret is cleared from the password field');
assert.deepEqual(calls.find(c=>c.data?.api_key).data,{api_key:'test-key'});
assert.ok(find(settings,'API key configured.'));
console.log('PASS: reference dialog checks unsaved text without saving, renders differences, and clears saved credentials');
