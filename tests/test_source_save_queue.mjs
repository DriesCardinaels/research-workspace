// Revision/text snapshots belong to execution time; queued saves cannot overwrite newer work.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const window={};
vm.runInNewContext(readFileSync(new URL('../static/editors/source/save-queue.js',import.meta.url),'utf8'),{window});
const {SourceSaveQueue}=window;
const queue=new SourceSaveQueue(),requests=[];
let text='first',saved='original',sha='r0';
const snapshot=()=>({text,saved,sha});
const persist=value=>new Promise((resolve,reject)=>requests.push({value,resolve,reject}));
const accept=(value,response)=>{saved=value;sha=response.sha;};
const first=queue.save(snapshot,persist,accept);
assert.equal(requests[0].value.text,'first','idle save captures immediately');
text='second';const second=queue.save(snapshot,persist,accept);text='latest';
requests[0].resolve({sha:'r1'});await first;
for(let i=0;i<5&&requests.length<2;i++)await Promise.resolve();
assert.equal(requests[1].value.text,'latest','waiting save captures current buffer, not earlier queued text');
assert.equal(requests[1].value.sha,'r1','waiting save uses the accepted revision');
text='edited during write';requests[1].resolve({sha:'r2'});await second;
assert.equal(saved,'latest');assert.notEqual(text,saved,'edits during IO remain dirty');
const failed=queue.save(snapshot,persist,accept);
const follower=queue.save(snapshot,persist,accept);
const failures=Promise.allSettled([failed,follower]);
requests[2].reject(Error('conflict'));await failures;
assert.equal(requests.length,3,'failed predecessor prevents dependent queued writes');
assert.equal(saved,'latest');assert.equal(sha,'r2');assert.equal(queue.pending,null);
const retry=queue.save(snapshot,persist,accept);requests[3].resolve({sha:'r3'});await retry;
assert.equal(saved,text);
assert.equal(await queue.save(snapshot,persist,accept),null);
const closing=new SourceSaveQueue();let activeResolve,writes=0;
const active=closing.save(()=>({text:'a',saved:'',sha:'r0'}),()=>new Promise(resolve=>{activeResolve=resolve;writes++;}),()=>{});
const waiting=closing.save(()=>({text:'b',saved:'',sha:'r0'}),async()=>{writes++;return {};},()=>{});
const closingResults=Promise.allSettled([active,waiting]);closing.dispose();activeResolve({sha:'r1'});
const outcomes=await closingResults;assert.equal(outcomes[0].status,'fulfilled');assert.equal(outcomes[1].status,'rejected');
assert.equal(writes,1);await assert.rejects(closing.save(snapshot,persist,accept),/closed/);
console.log('PASS: immediate/queued snapshots, accepted revisions, in-flight edits, failed predecessors, retries and disposal');
