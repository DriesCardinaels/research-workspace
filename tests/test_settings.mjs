assert.equal(all(dialog).find(n=>n.getAttribute('role')==='tablist').getAttribute('aria-orientation'),'horizontal');
integrations.events.keydown({key:'ArrowRight',preventDefault(){}});assert.equal(document.activeElement,appearance);
appearance.events.keydown({key:'ArrowLeft',preventDefault(){}});assert.equal(document.activeElement,integrations);
