const context=vm.createContext({document,api,matchMedia:()=>narrow,CodeMirror:{defineMode(){}},localStorage:storage,
  addEventListener(type,fn){if(type==='storage')listeners.add(fn);},removeEventListener(type,fn){if(type==='storage')listeners.delete(fn);},
  WorkbenchAppearance:{mount(host){assert.ok(host.isConnected);const section=document.createElement('section');host.append(section);return section;},unmount(){appearanceUnmounts++;}},
});context.window=context;
for(const file of ['spelling.js','bibliography.js','settings.js'])vm.runInContext(withPaneRuntime(readFileSync(new URL('../static/'+file,import.meta.url),'utf8')),context);
const {Tool}=context.EditorTools,origin=document.createElement('button');document.body.append(origin);origin.focus();
const all=node=>[node,...node.children.flatMap(all)];
const byId=(host,id)=>all(host).find(n=>n.id===id);
const byText=(host,text)=>all(host).find(n=>n.textContent===text);
let dialog=context.openSettings(),appearance=byId(dialog,'settingsTab-appearance'),writing=byId(dialog,'settingsTab-writing'),integrations=byId(dialog,'settingsTab-integrations');
