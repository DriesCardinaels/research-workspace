import {createDocument} from './support/pane-dom.mjs';
import {withPaneRuntime} from './support/tool-runtime.mjs';
const document=createDocument(),saved=new Map(),listeners=new Set();
const storage={get length(){return saved.size;},key:i=>[...saved.keys()][i],getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
let failRead=true,appearanceUnmounts=0;
const mediaListeners=new Set(),narrow={matches:false,addEventListener(type,fn){mediaListeners.add(fn);},removeEventListener(type,fn){mediaListeners.delete(fn);}};
