assert.equal(dialog.open,true);assert.equal(document.activeElement,appearance);
assert.equal(appearance.getAttribute('aria-selected'),'true');
assert.ok([appearance,writing,integrations].every(tab=>tab.getAttribute('data-tooltip')==='off'));
assert.equal(appearance.getAttribute('data-tool-label'),'Appearance','visible tabs retain concrete Tool metadata');
await new Promise(resolve=>setImmediate(resolve));
assert.ok(byText(dialog,'Integration unavailable'),'integration failure is local');
await Tool.activate(writing);
assert.equal(byId(dialog,'settingsPanel-writing').hidden,false);
assert.equal(byId(dialog,'settingsPanel-appearance').hidden,true);
const language=byId(dialog,'settingsSpellingLanguage');language.value='off';language.events.change();
assert.equal(context.Spelling.service.language,'off');
context.Spelling.service.setLanguage('nl');assert.equal(language.value,'nl','external changes update settings');
const dictionary=byId(dialog,'settingsDictionaryLanguage');dictionary.value='en-GB';dictionary.events.change();
